#!/usr/bin/env python3
"""Source of truth for SkyPanel's two bitmap faces. Emits `Fonts.cpp`.

Why hand-authored faces rather than one of the bundled Adafruit_GFX fonts: the panel is
64 px wide. The smallest font shipped with Adafruit_GFX is a 9 pt face whose caps are
7 px tall and ~6 px wide, which fits ten characters on a line. A telemetry line like
``24,000FT  410KT  6.1MI`` is 22 characters. It would scroll permanently, and a line
that never stops moving is a line nobody reads.

So there are two faces, both proportional (fixed-width wastes the panel on `I` and `1`):

  Tiny  5 px tall, 1–5 px wide, 1 px gap.  Body lines. ~19 characters across.
  Mid   7 px tall, 1–5 px wide, 1 px gap.  The airline name. ~11 characters across.

Both are uppercase-only by design — at five pixels tall, lowercase `a`/`e`/`s` collapse
into the same three-pixel blob, and descenders would eat a whole row of the panel.
`Text::draw` folds lowercase to uppercase, and the backend uppercases panel text too.

Three code points are repurposed as display glyphs, because the frame contract uses real
arrows and a five-pixel face has no room for a Unicode table:

    0x7B  {   ↑  climb
    0x7D  }   ↓  descend
    0x7E  ~   →  route separator

`Text` translates the UTF-8 arrows in the frame JSON into these slots.

Run:  python3 generate_fonts.py > Fonts.cpp
"""

