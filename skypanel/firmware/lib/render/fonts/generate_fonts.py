FIRST = 0x20
LAST = 0x7E


def rows_to_bytes(rows: list[str]) -> tuple[int, list[int]]:
    """Pack a glyph into one byte per row, MSB = leftmost pixel."""
    width = len(rows[0])
    if any(len(r) != width for r in rows):
        raise ValueError(f"ragged glyph: {rows}")
    if width > 8:
        raise ValueError(f"glyph wider than 8px: {rows}")
    packed = []
    for row in rows:
        value = 0
        for x, cell in enumerate(row):
            if cell == "#":
                value |= 1 << (7 - x)
        packed.append(value)
    return width, packed


def build(table: dict[str, list[str]], height: int) -> list[tuple[int, list[int]]]:
    """One entry per code point in [FIRST, LAST]; a–z reuse the uppercase glyph."""
    out = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        source = table.get(ch)
        if source is None and ch.isalpha():
            source = table.get(ch.upper())
        if source is None:
            source = table[" "]
        if len(source) != height:
            raise ValueError(f"glyph {ch!r} has {len(source)} rows, expected {height}")
        out.append(rows_to_bytes(source))
    return out


def emit(name: str, glyphs: list[tuple[int, list[int]]], height: int, out) -> None:
    print(f"const Glyph {name}Glyphs[] = {{", file=out)
    for code, (width, rows) in zip(range(FIRST, LAST + 1), glyphs, strict=True):
        packed = ", ".join(f"0x{r:02X}" for r in rows)
        label = chr(code) if chr(code) not in "\\'" else f"\\{chr(code)}"
        print(f"    {{{width}, {{{packed}}}}},  // 0x{code:02X} '{label}'", file=out)
    print("};\n", file=out)
    print(f"const BitmapFont {name} = {{", file=out)
    print(f'    "{name}", {height}, 1, {FIRST}, {LAST - FIRST + 1}, {name}Glyphs}};\n', file=out)


def main() -> None:
    out = sys.stdout
    print("// GENERATED by generate_fonts.py — do not edit by hand.", file=out)
    print("// Re-run:  python3 generate_fonts.py > Fonts.cpp\n", file=out)
    print('#include "Fonts.h"\n', file=out)
    print("namespace skypanel {\nnamespace {\n", file=out)
    emit("FontTinyData", build(TINY, 5), 5, out)
    emit("FontMidData", build(MID, 7), 7, out)
    print("}  // namespace\n", file=out)
    print("const BitmapFont &FontTiny = FontTinyData;", file=out)
    print("const BitmapFont &FontMid = FontMidData;\n", file=out)
    print("}  // namespace skypanel", file=out)


if __name__ == "__main__":
    main()
